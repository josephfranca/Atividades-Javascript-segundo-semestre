// Faça um script  para calcular e mostrar a área de um triângulo. Lembre-se: área = (base * altura) /2.
let base = parseFloat(prompt("Digite a base de seu triângulo: "))
let altura = parseFloat(prompt("Digite a altura de seu triângulo: "))

let area = (base * altura) / 2
alert("A área do seu triângulo é de:  " + area) 